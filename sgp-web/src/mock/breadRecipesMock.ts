export function formatCurrencyFromCents(valueInCents: number): string {
  return new Intl.NumberFormat('pt-BR', {
    style: 'currency',
    currency: 'BRL',
  }).format(valueInCents / 100);
}

export function getIngredientById(ingredientId: number): Ingredient | undefined {
  return breadIngredients.find((ingredient) => ingredient.id === ingredientId);
}

export function calculateRecipeCost(recipe: BreadRecipe): number {
  return recipe.ingredients.reduce((total, item) => {
    const ingredient = getIngredientById(item.ingredientId);

    if (!ingredient) {
      return total;
    }

    return total + ingredient.costPerUnit * item.quantity;
  }, 0);
}

export function calculateCostPerUnit(recipe: BreadRecipe): number {
  return calculateRecipeCost(recipe) / recipe.yieldUnits;
}

export function calculateEstimatedProfitPerUnit(recipe: BreadRecipe): number {
  return recipe.salePriceInCents / 100 - calculateCostPerUnit(recipe);
}
